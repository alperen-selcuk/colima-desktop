/// Run every declared preflight check for `item` against `profile`'s VM,
/// plus the implicit "compose available" check. Never touches installed
/// instance state; safe to call repeatedly (e.g. from `marketplace_prepare`
/// and standalone `marketplace_preflight`).
async fn run_preflight(state: &AppState, profile: &str, item: &CatalogItem) -> Result<Vec<PreflightResult>, String> {
    let mut results = Vec::new();

    let status = crate::colima::profile_status(profile.to_string()).await?;
    let Some(status) = status else {
        return Err(format!("{profile} is not running — start it first"));
    };

    results.push(evaluate_arch_preflight(&status.arch, &item.architectures));
    if let Some(mem_check) = evaluate_memory_preflight(status.memory, item.min_memory_mb) {
        results.push(mem_check);
    }

    for check in &item.preflight {
        let CatalogPreflightCheck::Sysctl { key, min } = check;
        if !is_valid_sysctl_key(key) {
            results.push(PreflightResult {
                id: format!("sysctl:{key}"),
                ok: false,
                severity: "error".to_string(),
                message: format!("invalid sysctl key in catalog: {key:?}"),
                fixable: false,
            });
            continue;
        }
        let current = exec::run("colima", &["ssh", "-p", profile, "--", "sysctl", "-n", key])
            .await
            .ok()
            .and_then(|out| out.trim().parse::<i64>().ok());
        results.push(evaluate_sysctl_preflight(key, *min, current));
    }

    let socket = resolve_docker_socket(state, profile).await;
    let compose_info = compose::resolve_compose_info(state, profile, &socket).await;
    results.push(evaluate_compose_preflight(compose_info.available));

    Ok(results)
}

#[tauri::command]
pub async fn marketplace_preflight(app: AppHandle, state: State<'_, AppState>, profile: String, item_id: String) -> Result<Vec<PreflightResult>, String> {
    validate_profile_name(&profile)?;
    validate_item_id(&item_id)?;
    let item = find_catalog_item(&app, &item_id).await?;
    run_preflight(&state, &profile, &item).await
}

/// `marketplace_fix_preflight`: apply the fix for one preflight check id.
/// Only `sysctl:<key>` checks are fixable today (§6.8): run `colima ssh -p
/// <p> -- sudo sysctl -w key=value`, then persist it across VM restarts by
/// appending/overwriting the key in `/etc/sysctl.d/99-colima-desktop.conf`
/// inside the VM. Requires re-running `marketplace_preflight` to learn the
/// `min` value again (the check id alone doesn't carry it), so this command
/// takes the full item to look the check back up — but the IPC contract
/// (§6.8) is `profile, checkId` only, so we resolve the min from the
/// currently cached/fetched catalog by scanning every item's preflight list
/// for a `sysctl` check whose key matches `checkId`'s suffix. If multiple
/// catalog items declare the same key with different minimums, the largest
/// minimum wins (the safer value).
#[tauri::command]
pub async fn marketplace_fix_preflight(app: AppHandle, profile: String, check_id: String) -> Result<(), String> {
    validate_profile_name(&profile)?;
    let key = check_id
        .strip_prefix("sysctl:")
        .ok_or_else(|| format!("check {check_id:?} is not fixable"))?;
    if !is_valid_sysctl_key(key) {
        return Err(format!("invalid sysctl key: {key:?}"));
    }

    let catalog = marketplace_catalog(app, false).await?;
    let min = catalog
        .items
        .iter()
        .flat_map(|i| i.preflight.iter())
        .filter_map(|c| {
            let CatalogPreflightCheck::Sysctl { key: k, min } = c;
            (k == key).then_some(*min)
        })
        .max()
        .ok_or_else(|| format!("no catalog item declares a sysctl check for {key}"))?;

    apply_sysctl_fix(&profile, key, min).await
}

/// Apply `colima ssh -p <p> -- sudo sysctl -w key=value`, then persist it in
/// `/etc/sysctl.d/99-colima-desktop.conf` inside the VM. `key` must already
/// be validated against `^[a-z0-9_.]+$`; `min` (an `i64`) is always a
/// digits-only value once formatted, satisfying [`is_valid_sysctl_value`].
async fn apply_sysctl_fix(profile: &str, key: &str, min: i64) -> Result<(), String> {
    if !is_valid_sysctl_key(key) {
        return Err(format!("invalid sysctl key: {key:?}"));
    }
    let value = min.to_string();
    if !is_valid_sysctl_value(&value) {
        return Err(format!("invalid sysctl value for {key}: {value:?}"));
    }

    let assignment = format!("{key}={value}");
    exec::run("colima", &["ssh", "-p", profile, "--", "sudo", "sysctl", "-w", &assignment]).await?;

    // Persist: append (or replace) the line in
    // /etc/sysctl.d/99-colima-desktop.conf so it survives VM restarts. Build
    // the in-VM shell snippet from already-validated key/value only (never
    // from unvalidated catalog/user text) and quote the whole snippet with
    // single quotes for `sh -c`.
    let conf_path = "/etc/sysctl.d/99-colima-desktop.conf";
    let script = format!(
        "touch {conf_path} && (grep -q '^{key}=' {conf_path} && sed -i 's/^{key}=.*/{key}={value}/' {conf_path} || echo '{key}={value}' >> {conf_path})"
    );
    exec::run("colima", &["ssh", "-p", profile, "--", "sudo", "sh", "-c", &script]).await?;
    Ok(())
}

