/// Validate a marketplace item id: `^[a-z0-9][a-z0-9-]*$` (§6.8's app.json
/// `id` rule).
pub fn is_valid_item_id(id: &str) -> bool {
    if id.is_empty() {
        return false;
    }
    let mut chars = id.chars();
    let first = chars.next().unwrap();
    if !(first.is_ascii_lowercase() || first.is_ascii_digit()) {
        return false;
    }
    chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
}

pub fn validate_item_id(id: &str) -> Result<(), String> {
    if is_valid_item_id(id) {
        Ok(())
    } else {
        Err(format!("invalid marketplace item id: {id:?}"))
    }
}

/// Default project name for an item: `cd-<id>`, suffixed `-2`, `-3`, … if
/// taken (compared against `taken`, e.g. existing instance dirs).
pub fn default_project_name(item_id: &str, taken: &HashSet<String>) -> String {
    let base = format!("cd-{item_id}");
    if !taken.contains(&base) {
        return base;
    }
    let mut n = 2u32;
    loop {
        let candidate = format!("{base}-{n}");
        if !taken.contains(&candidate) {
            return candidate;
        }
        n += 1;
    }
}

/// Substitute `${VAR}` placeholders in `template` from `values`. Unknown
/// variables are left as-is (not substituted) rather than erroring, since
/// endpoint/ready templates are trusted catalog content, not user input.
pub fn render_template(template: &str, values: &HashMap<String, String>) -> String {
    let mut out = String::with_capacity(template.len());
    let bytes = template.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'$' && i + 1 < bytes.len() && bytes[i + 1] == b'{' {
            if let Some(end) = template[i + 2..].find('}') {
                let var_name = &template[i + 2..i + 2 + end];
                if let Some(value) = values.get(var_name) {
                    out.push_str(value);
                } else {
                    out.push_str(&template[i..i + 2 + end + 1]);
                }
                i += 2 + end + 1;
                continue;
            }
        }
        // Push one char (handling multi-byte UTF-8 correctly).
        let ch = template[i..].chars().next().unwrap();
        out.push(ch);
        i += ch.len_utf8();
    }
    out
}

/// CSPRNG alphanumeric password of `length` characters (mixed-case letters +
/// digits; URL/YAML-safe per §6.8's "Passwords alphanumeric" rule).
pub fn generate_password(length: u32) -> String {
    const ALPHABET: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
    let len = length.max(1) as usize;
    let mut bytes = vec![0u8; len];
    getrandom::getrandom(&mut bytes).expect("system CSPRNG must be available");
    bytes.iter().map(|b| ALPHABET[(*b as usize) % ALPHABET.len()] as char).collect()
}

/// Whether `port` is free: not present in `taken` (the union of host-bound
/// TCP listeners on 127.0.0.1/0.0.0.0, docker-published ports, and ports
/// reserved by other marketplace instances' `.env` files — the caller
/// assembles `taken` via [`collect_taken_ports`] / a live bind test).
pub fn is_port_free(port: u16, taken: &HashSet<u16>) -> bool {
    !taken.contains(&port)
}

/// Live bind test: true if `port` can be bound on both 127.0.0.1 and
/// 0.0.0.0 (i.e. genuinely free at the OS level right now).
fn port_bind_free(port: u16) -> bool {
    TcpListener::bind(("127.0.0.1", port)).is_ok() && TcpListener::bind(("0.0.0.0", port)).is_ok()
}

/// Extract host-bound TCP ports already used by other marketplace instances
/// from their `.env` files: any `KEY=VALUE` line whose value parses as a
/// bare u16, for every instance dir under `<profile_dir>` except
/// `exclude_project` (the instance currently being prepared/re-saved, if
/// any).
fn ports_reserved_by_other_instances(profile_dir: &Path, exclude_project: Option<&str>) -> HashSet<u16> {
    let mut ports = HashSet::new();
    let Ok(entries) = std::fs::read_dir(profile_dir) else {
        return ports;
    };
    for entry in entries.flatten() {
        let Ok(file_type) = entry.file_type() else { continue };
        if !file_type.is_dir() {
            continue;
        }
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if Some(name.as_ref()) == exclude_project {
            continue;
        }
        let env_path = entry.path().join(".env");
        let Ok(content) = std::fs::read_to_string(&env_path) else { continue };
        for (_k, v) in parse_env_lines(&content) {
            if let Ok(p) = v.parse::<u16>() {
                ports.insert(p);
            }
        }
    }
    ports
}

/// Resolve the requested/default port for a `port`-typed variable to an
/// actually-free port: prefer the requested default; if taken, scan upward.
/// `taken` should already include reserved-by-other-instances and
/// docker-published ports; this also live-bind-tests each candidate so a
/// port free on disk-state but held by some unrelated process is skipped.
fn resolve_free_port(default: u16, taken: &HashSet<u16>) -> u16 {
    let mut candidate = default;
    loop {
        if is_port_free(candidate, taken) && port_bind_free(candidate) {
            return candidate;
        }
        candidate = candidate.saturating_add(1);
        if candidate == 0 {
            // wrapped (started at 65535); give up and return the original
            // default rather than looping forever.
            return default;
        }
    }
}

/// Parse simple `KEY=VALUE` lines from an `.env`-style file (one per line,
/// `#`-prefixed/blank lines skipped, values may be double-quoted). Used both
/// to scan reserved ports and, in tests, to verify serialisation round-trips.
pub fn parse_env_lines(content: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for line in content.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let Some((k, v)) = line.split_once('=') else { continue };
        let v = v.trim();
        let v = if v.len() >= 2 && v.starts_with('"') && v.ends_with('"') {
            unescape_env_value(&v[1..v.len() - 1])
        } else {
            v.to_string()
        };
        out.push((k.trim().to_string(), v));
    }
    out
}

fn unescape_env_value(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut chars = s.chars();
    while let Some(c) = chars.next() {
        if c == '\\' {
            match chars.next() {
                Some('"') => out.push('"'),
                Some('\\') => out.push('\\'),
                Some('n') => out.push('\n'),
                Some(other) => {
                    out.push('\\');
                    out.push(other);
                }
                None => out.push('\\'),
            }
        } else {
            out.push(c);
        }
    }
    out
}

/// Escape one value for a double-quoted `.env` line: backslash then quote
/// characters escaped, embedded newlines escaped, so the file round-trips
/// through both this parser and docker compose's own `.env` reader (which
/// also honors double-quoted values with the same two escapes).
fn escape_env_value(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for c in value.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            other => out.push(other),
        }
    }
    out
}

/// Serialise an ordered list of `(key, value)` pairs into `.env` file
/// content: one `KEY="escaped value"` line per pair, trailing newline. Every
/// value is double-quoted so blank/special-character values are unambiguous.
pub fn serialize_env_file(pairs: &[(String, String)]) -> String {
    let mut out = String::new();
    for (k, v) in pairs {
        out.push_str(k);
        out.push_str("=\"");
        out.push_str(&escape_env_value(v));
        out.push_str("\"\n");
    }
    out
}

/// Validate a sysctl key against `^[a-z0-9_.]+$` (§6.8's fix-preflight rule:
/// keys/values come from the catalog but must be validated before building
/// an in-VM shell command).
pub fn is_valid_sysctl_key(key: &str) -> bool {
    !key.is_empty() && key.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_' || c == '.')
}

/// Validate a sysctl value: digits only (every catalog sysctl check today is
/// an integer minimum; keeping this strict avoids ever building a shell
/// command from an unvalidated string).
pub fn is_valid_sysctl_value(value: &str) -> bool {
    !value.is_empty() && value.chars().all(|c| c.is_ascii_digit())
}

/// Parsed `colima status --json` arch string, mapped to catalog
/// architecture ids (§6.8: `aarch64`->`arm64`, `x86_64`->`amd64`).
pub fn normalize_arch(colima_arch: &str) -> String {
    match colima_arch {
        "aarch64" => "arm64".to_string(),
        "x86_64" => "amd64".to_string(),
        other => other.to_string(),
    }
}

/// Evaluate the `arch` preflight check: error if `architectures` is
/// non-empty and doesn't contain the normalized VM arch.
pub fn evaluate_arch_preflight(vm_arch: &str, architectures: &[String]) -> PreflightResult {
    let normalized = normalize_arch(vm_arch);
    let ok = architectures.is_empty() || architectures.iter().any(|a| a == &normalized);
    PreflightResult {
        id: "arch".to_string(),
        ok,
        severity: "error".to_string(),
        message: if ok {
            format!("architecture {normalized} is supported")
        } else {
            format!("this app supports {} but the machine is {normalized}", architectures.join(", "))
        },
        fixable: false,
    }
}

/// Evaluate the `memory` preflight check: warning if VM memory (bytes) is
/// below `min_memory_mb`.
pub fn evaluate_memory_preflight(vm_memory_bytes: u64, min_memory_mb: Option<u64>) -> Option<PreflightResult> {
    let min_mb = min_memory_mb?;
    let vm_mb = vm_memory_bytes / (1024 * 1024);
    let ok = vm_mb >= min_mb;
    Some(PreflightResult {
        id: "memory".to_string(),
        ok,
        severity: "warning".to_string(),
        message: if ok {
            format!("{vm_mb} MiB available (recommended {min_mb} MiB)")
        } else {
            format!("machine has {vm_mb} MiB; {min_mb} MiB recommended for this app")
        },
        fixable: false,
    })
}

/// Evaluate one `sysctl` preflight check from a value already read from the
/// VM (`colima ssh -p <p> -- sysctl -n <key>`); `current` is `None` if the
/// read failed.
pub fn evaluate_sysctl_preflight(key: &str, min: i64, current: Option<i64>) -> PreflightResult {
    let id = format!("sysctl:{key}");
    match current {
        Some(v) if v >= min => PreflightResult {
            id,
            ok: true,
            severity: "error".to_string(),
            message: format!("{key}={v} (>= {min})"),
            fixable: true,
        },
        Some(v) => PreflightResult {
            id,
            ok: false,
            severity: "error".to_string(),
            message: format!("{key}={v}, needs >= {min}"),
            fixable: true,
        },
        None => PreflightResult {
            id,
            ok: false,
            severity: "error".to_string(),
            message: format!("could not read {key} from the VM"),
            fixable: true,
        },
    }
}

/// Evaluate the `compose available` preflight check.
pub fn evaluate_compose_preflight(available: bool) -> PreflightResult {
    PreflightResult {
        id: "compose".to_string(),
        ok: available,
        severity: "error".to_string(),
        message: if available {
            "Docker Compose is available".to_string()
        } else {
            "Docker Compose is not available".to_string()
        },
        fixable: false,
    }
}

/// Whether a ready-check's HTTP status counts as "ready" (§6.8: `expectStatus`).
pub fn http_status_is_ready(status: u16, expect: &[u16]) -> bool {
    expect.contains(&status)
}

/// Parse `compose ps --format json` (JSON-lines, one object per line) health
/// values and decide if every service with a health status reports
/// `"healthy"`. Services with no `Health` field (no healthcheck defined) are
/// ignored, matching §6.8's "all services with healthchecks report healthy".
/// Returns `false` (not ready) if there is not at least one reporting a
/// health value at all AND the list is non-empty but nothing is healthy yet;
/// an empty list (no containers yet) is also not ready.
pub fn evaluate_healthy_ready(statuses: &[Option<String>]) -> bool {
    if statuses.is_empty() {
        return false;
    }
    let with_health: Vec<&String> = statuses.iter().filter_map(|s| s.as_ref()).collect();
    if with_health.is_empty() {
        // No service declares a healthcheck: "healthy" degenerates to
        // "everything is at least present", which `running`-style callers
        // handle separately; treat as ready once containers exist.
        return true;
    }
    with_health.iter().all(|s| s.as_str() == "healthy")
}

/// Validate a value for a catalog variable's declared type before it's
/// written into `.env`/rendered into a compose file: `port` must parse as
/// u16, `password`/`string` accept any non-empty (for password) or any
/// string (for string) value. Returns `Err` with a human message on
/// mismatch.
pub fn validate_variable_value(var: &CatalogVariable, value: &str) -> Result<(), String> {
    match var.var_type.as_str() {
        "port" => {
            value
                .parse::<u16>()
                .map(|_| ())
                .map_err(|_| format!("{}: must be a valid port number", var.name))?;
            Ok(())
        }
        "password" => {
            if value.is_empty() {
                return Err(format!("{}: password must not be empty", var.name));
            }
            if !value.chars().all(|c| c.is_ascii_alphanumeric()) {
                return Err(format!("{}: password must be alphanumeric", var.name));
            }
            Ok(())
        }
        "string" => Ok(()),
        other => Err(format!("{}: unknown variable type {other:?}", var.name)),
    }
}

/// Build the ordered `(key, value)` pairs to write to `.env`: every variable
/// value plus `COMPOSE_PROJECT_NAME`.
pub fn build_env_pairs(values: &HashMap<String, String>, project_name: &str, var_order: &[String]) -> Vec<(String, String)> {
    let mut pairs = Vec::with_capacity(values.len() + 1);
    for name in var_order {
        if let Some(v) = values.get(name) {
            pairs.push((name.clone(), v.clone()));
        }
    }
    // Any values not covered by var_order (shouldn't normally happen) still
    // get written, sorted for determinism.
    let mut extra: Vec<&String> = values.keys().filter(|k| !var_order.contains(k)).collect();
    extra.sort();
    for k in extra {
        pairs.push((k.clone(), values[k].clone()));
    }
    pairs.push(("COMPOSE_PROJECT_NAME".to_string(), project_name.to_string()));
    pairs
}

/// Render every declared endpoint's templated fields using `values`.
pub fn render_endpoints(endpoints: &[CatalogEndpoint], values: &HashMap<String, String>) -> Vec<InstalledEndpoint> {
    endpoints
        .iter()
        .map(|e| InstalledEndpoint {
            name: e.name.clone(),
            url: e.url.as_ref().map(|u| render_template(u, values)),
            value: e.value.as_ref().map(|v| render_template(v, values)),
            username: e.username.as_ref().map(|u| render_template(u, values)),
            password: e.password.as_ref().map(|p| render_template(p, values)),
            primary: e.primary,
        })
        .collect()
}

/// The marketplace root: `<app_data_dir>/marketplace`.
fn marketplace_root(app_data_dir: &Path) -> PathBuf {
    app_data_dir.join("marketplace")
}

/// `<marketplace_root>/<profile>`.
fn profile_marketplace_dir(app_data_dir: &Path, profile: &str) -> PathBuf {
    marketplace_root(app_data_dir).join(profile)
}

/// `<marketplace_root>/<profile>/<projectName>`.
fn instance_dir(app_data_dir: &Path, profile: &str, project_name: &str) -> PathBuf {
    profile_marketplace_dir(app_data_dir, profile).join(project_name)
}

/// Guard against path traversal: `project_name` must be a plain compose
/// project name (already validated elsewhere) and the resolved instance dir
/// must actually be inside the marketplace root for this profile. Used
/// before any destructive filesystem operation on an instance dir.
fn instance_dir_within_root(app_data_dir: &Path, profile: &str, project_name: &str) -> Result<PathBuf, String> {
    if !compose::is_valid_project_name(project_name) {
        return Err(format!("invalid project name: {project_name:?}"));
    }
    let root = profile_marketplace_dir(app_data_dir, profile);
    let dir = instance_dir(app_data_dir, profile, project_name);
    // Purely lexical containment check (the dir may not exist yet, so we
    // can't canonicalize): root is `<app_data_dir>/marketplace/<profile>`
    // and dir is always `root.join(project_name)` above, but re-verify via
    // `strip_prefix` so any future refactor can't silently break this.
    dir.strip_prefix(&root).map_err(|_| "instance path escapes the marketplace root".to_string())?;
    Ok(dir)
}

fn write_atomically(path: &Path, content: &[u8], mode: Option<u32>) -> Result<(), String> {
    let dir = path.parent().ok_or_else(|| "invalid instance path".to_string())?;
    std::fs::create_dir_all(dir).map_err(|e| format!("failed to create instance directory: {e}"))?;
    let file_name = path.file_name().ok_or_else(|| "invalid instance path".to_string())?.to_string_lossy();
    let tmp_path = dir.join(format!(".{file_name}.tmp-{}", std::process::id()));

    let result = (|| -> Result<(), String> {
        let mut file = std::fs::File::create(&tmp_path).map_err(|e| format!("failed to write file: {e}"))?;
        file.write_all(content).map_err(|e| format!("failed to write file: {e}"))?;
        file.sync_all().map_err(|e| format!("failed to write file: {e}"))?;
        #[cfg(unix)]
        if let Some(mode) = mode {
            use std::os::unix::fs::PermissionsExt;
            let mut perms = file.metadata().map_err(|e| format!("failed to write file: {e}"))?.permissions();
            perms.set_mode(mode);
            std::fs::set_permissions(&tmp_path, perms).map_err(|e| format!("failed to write file: {e}"))?;
        }
        #[cfg(not(unix))]
        let _ = mode;
        Ok(())
    })();

    if let Err(e) = result {
        let _ = std::fs::remove_file(&tmp_path);
        return Err(e);
    }
    std::fs::rename(&tmp_path, path).map_err(|e| {
        let _ = std::fs::remove_file(&tmp_path);
        format!("failed to write file: {e}")
    })
}

fn app_data_dir_of(app: &AppHandle) -> Result<PathBuf, String> {
    app.path().app_data_dir().map_err(|e| format!("could not resolve app data dir: {e}"))
}

