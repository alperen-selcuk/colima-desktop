#[tauri::command]
pub async fn marketplace_uninstall(
    app: AppHandle,
    state: State<'_, AppState>,
    profile: String,
    project_name: String,
    remove_volumes: bool,
) -> Result<(), String> {
    validate_profile_name(&profile)?;
    compose::validate_project_name(&project_name)?;

    let app_data_dir = app_data_dir_of(&app)?;
    let dir = instance_dir_within_root(&app_data_dir, &profile, &project_name)?;

    if dir.is_dir() {
        let socket = resolve_docker_socket(&state, &profile).await;
        if let Some(mode) = compose::resolve_compose_info(&state, &profile, &socket).await.mode {
            let lock_key = format!("compose:{project_name}");
            let _guard = state.try_lock_profile(&lock_key)?;

            let compose_path = dir.join("compose.yml");
            let config_files = if compose_path.is_file() {
                vec![compose_path.to_string_lossy().to_string()]
            } else {
                Vec::new()
            };
            if let Ok((bin, args)) = compose::build_action_args(mode, &socket, &project_name, "down", &config_files, remove_volumes) {
                let arg_refs: Vec<&str> = args.iter().map(String::as_str).collect();
                let env_overrides = compose_env_for_mode(mode, &socket);
                let env_refs: Vec<(&str, &str)> = env_overrides.iter().map(|(k, v)| (k.as_str(), v.as_str())).collect();
                let _ = exec::run_streaming_with_env(&app, &bin, &arg_refs, &profile, "marketplace-uninstall", &env_refs, Some(&dir)).await;
            }
        }
    }

    // Remove the instance dir — guarded above to stay within the
    // marketplace root for this profile.
    if dir.exists() {
        std::fs::remove_dir_all(&dir).map_err(|e| format!("failed to remove instance directory: {e}"))?;
    }

    let _ = app.emit("profiles-changed", ());
    Ok(())
}

