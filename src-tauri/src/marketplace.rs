//! Marketplace: one-click apps & stacks (§6.8, docs/SPEC.md). Users pick a
//! curated catalog item (an app.json + compose.yml pair), the backend
//! renders variable values (passwords, ports, etc.) into a compose project
//! under `<app_data_dir>/marketplace/<profile>/<projectName>/`, brings it up
//! with `docker compose` (reusing `compose.rs`'s mode resolution/streaming),
//! waits for the declared readiness condition, and returns rendered
//! endpoints (URLs/credentials/connection strings).
//!
//! The built-in catalog is embedded at compile time from
//! `catalog/dist/catalog.json` (generated by `npm run catalog:build`; see
//! `catalog/README.md`). A remote copy is fetched from GitHub and cached on
//! disk for 6h (same shape as `k3s.rs`'s version cache), falling back to a
//! stale cache on network error and finally to the built-in copy.

