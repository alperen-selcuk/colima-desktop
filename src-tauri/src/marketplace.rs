#[tauri::command]
pub async fn marketplace_install(
    app: AppHandle,
    state: State<'_, AppState>,
    profile: String,
    item_id: String,
    project_name: String,
    values: HashMap<String, String>,
) -> Result<InstalledApp, String> {
    validate_profile_name(&profile)?;
    validate_item_id(&item_id)?;
    compose::validate_project_name(&project_name)?;

    let item = find_catalog_item(&app, &item_id).await?;
    if item.compose.trim().is_empty() {
        return Err(format!("catalog item {item_id} has no compose definition"));
    }

    // Re-validate every declared variable's value (types + port freeness),
    // per §6.8's "re-validate values" instruction.
    let app_data_dir = app_data_dir_of(&app)?;
    let mut taken_ports = collect_taken_ports(&app, &state, &profile, Some(&project_name)).await;

    let mut var_order = Vec::with_capacity(item.variables.len());
    for var in &item.variables {
        var_order.push(var.name.clone());
        let value = values
            .get(&var.name)
            .ok_or_else(|| format!("missing value for variable {}", var.name))?;
        validate_variable_value(var, value)?;
        if var.var_type == "port" {
            let port: u16 = value.parse().map_err(|_| format!("{}: invalid port", var.name))?;
            if !is_port_free(port, &taken_ports) {
                return Err(format!("{}: port {port} is already in use", var.name));
            }
            taken_ports.insert(port);
        }
    }

    let dir = instance_dir_within_root(&app_data_dir, &profile, &project_name)?;
    std::fs::create_dir_all(&dir).map_err(|e| format!("failed to create instance directory: {e}"))?;

    // Write compose.yml verbatim.
    let compose_path = dir.join("compose.yml");
    write_atomically(&compose_path, item.compose.as_bytes(), None)?;

    // Write .env (mode 0600).
    let env_pairs = build_env_pairs(&values, &project_name, &var_order);
    let env_content = serialize_env_file(&env_pairs);
    let env_path = dir.join(".env");
    write_atomically(&env_path, env_content.as_bytes(), Some(0o600))?;

    // Write instance.json.
    let manifest = InstanceManifest {
        item_id: item_id.clone(),
        name: item.name.clone(),
        icon: item.icon.clone(),
        project_name: project_name.clone(),
        created_at: iso_now(),
        catalog_generated_at: String::new(),
        values: values.clone(),
    };
    let manifest_json = serde_json::to_string_pretty(&manifest).map_err(|e| e.to_string())?;
    let manifest_path = dir.join("instance.json");
    write_atomically(&manifest_path, manifest_json.as_bytes(), None)?;

    // compose up -d
    let socket = resolve_docker_socket(&state, &profile).await;
    let mode = require_compose_mode(&state, &profile, &socket).await?;
    let lock_key = format!("compose:{project_name}");
    let _guard = state.try_lock_profile(&lock_key)?;

    let compose_files = vec![compose_path.to_string_lossy().to_string()];
    let (bin, args) = compose::build_up_args(mode, &socket, &compose_files, Some(&project_name), &ComposeUpOptions {
        build: false,
        pull: "missing".to_string(),
        force_recreate: false,
    });
    let arg_refs: Vec<&str> = args.iter().map(String::as_str).collect();
    let env_overrides = compose_env_for_mode(mode, &socket);
    let env_refs: Vec<(&str, &str)> = env_overrides.iter().map(|(k, v)| (k.as_str(), v.as_str())).collect();

    let up_result = exec::run_streaming_with_env(&app, &bin, &arg_refs, &profile, "marketplace-install", &env_refs, Some(&dir)).await;
    let _ = app.emit("profiles-changed", ());
    up_result?;

    // Wait for readiness, emitting progress lines on the same op log.
    let mut warning: Option<String> = None;
    if let Some(ready) = &item.ready {
        emit_op_log(&app, &profile, "marketplace-install", "waiting for the app to become ready…");
        if let Err(timeout_msg) = wait_ready(&app, &profile, &project_name, mode, &socket, ready).await {
            warning = Some(timeout_msg);
        } else {
            emit_op_log(&app, &profile, "marketplace-install", "ready.");
        }
    }

    let status = compose_project_status(&state, &profile, &project_name).await.unwrap_or_else(|| "unknown".to_string());
    let final_status = if warning.is_some() { "starting".to_string() } else { status };

    if let Some(w) = &warning {
        emit_op_log(&app, &profile, "marketplace-install", &format!("warning: {w}"));
    }

    Ok(InstalledApp {
        project_name,
        item_id,
        name: item.name,
        icon: item.icon,
        created_at: manifest.created_at,
        status: final_status,
        endpoints: render_endpoints(&item.endpoints, &values),
        notes: item.notes,
    })
}

fn emit_op_log(app: &AppHandle, profile: &str, op: &str, line: &str) {
    let _ = app.emit(
        "colima-op-log",
        exec::OpLog { profile: profile.to_string(), op: op.to_string(), line: line.to_string() },
    );
}

async fn require_compose_mode(state: &AppState, profile: &str, socket: &str) -> Result<ComposeMode, String> {
    let info = compose::resolve_compose_info(state, profile, socket).await;
    info.mode.ok_or_else(|| "Docker Compose is not available".to_string())
}

fn compose_env_for_mode(mode: ComposeMode, socket: &str) -> Vec<(String, String)> {
    match mode {
        ComposeMode::Plugin => Vec::new(),
        ComposeMode::Standalone => vec![("DOCKER_HOST".to_string(), socket.to_string())],
    }
}

/// Poll the declared readiness condition every 2s until ready or timeout.
/// Returns `Err(message)` on timeout (never on transient poll errors, which
/// are just retried).
async fn wait_ready(app: &AppHandle, profile: &str, project: &str, mode: ComposeMode, socket: &str, ready: &CatalogReady) -> Result<(), String> {
    let timeout_sec = match ready {
        CatalogReady::Http { timeout_sec, .. } => *timeout_sec,
        CatalogReady::Healthy { timeout_sec } => *timeout_sec,
        CatalogReady::Running { timeout_sec } => *timeout_sec,
    };

    let deadline = tokio::time::Instant::now() + Duration::from_secs(timeout_sec);
    let mut elapsed = 0u64;
    loop {
        let is_ready = match ready {
            CatalogReady::Http { url, expect_status, .. } => poll_http_ready(url, expect_status).await,
            CatalogReady::Healthy { .. } => poll_healthy_ready(mode, socket, project).await,
            CatalogReady::Running { .. } => poll_running_ready(mode, socket, project).await,
        };
        if is_ready {
            return Ok(());
        }
        if tokio::time::Instant::now() >= deadline {
            return Err(format!("timed out after {timeout_sec}s waiting for readiness"));
        }
        tokio::time::sleep(Duration::from_secs(2)).await;
        elapsed += 2;
        emit_op_log(app, profile, "marketplace-install", &format!("still waiting for {project} to become ready… ({elapsed}s)"));
    }
}

async fn poll_http_ready(url: &str, expect: &[u16]) -> bool {
    let client = match reqwest::Client::builder().timeout(Duration::from_secs(5)).build() {
        Ok(c) => c,
        Err(_) => return false,
    };
    match client.get(url).send().await {
        Ok(resp) => http_status_is_ready(resp.status().as_u16(), expect),
        Err(_) => false,
    }
}

async fn poll_healthy_ready(mode: ComposeMode, socket: &str, project: &str) -> bool {
    let statuses = compose_ps_health(mode, socket, project).await;
    evaluate_healthy_ready(&statuses)
}

async fn poll_running_ready(mode: ComposeMode, socket: &str, project: &str) -> bool {
    let status = compose_project_status_raw(mode, socket, project).await;
    status.map(|s| s.to_lowercase().contains("running")).unwrap_or(false)
}

#[derive(Debug, Deserialize)]
struct RawComposePsEntry {
    #[serde(default)]
    #[serde(rename = "Health")]
    health: Option<String>,
}

/// `compose -p <project> ps --format json`'s per-service `Health` field for
/// every service (empty string when no healthcheck is defined, mapped to
/// `None`).
async fn compose_ps_health(mode: ComposeMode, socket: &str, project: &str) -> Vec<Option<String>> {
    let bin = match mode {
        ComposeMode::Plugin => "docker",
        ComposeMode::Standalone => "docker-compose",
    };
    let mut args: Vec<String> = match mode {
        ComposeMode::Plugin => vec!["-H".to_string(), socket.to_string(), "compose".to_string()],
        ComposeMode::Standalone => Vec::new(),
    };
    args.push("-p".to_string());
    args.push(project.to_string());
    args.push("ps".to_string());
    args.push("--format".to_string());
    args.push("json".to_string());
    let arg_refs: Vec<&str> = args.iter().map(String::as_str).collect();
    let stdout = match mode {
        ComposeMode::Plugin => exec::run(bin, &arg_refs).await,
        ComposeMode::Standalone => exec::run_with_env(bin, &arg_refs, &[("DOCKER_HOST", socket)]).await,
    };
    let Ok(stdout) = stdout else { return Vec::new() };
    let entries: Vec<RawComposePsEntry> = exec::parse_json_lines_or_array(&stdout).unwrap_or_default();
    entries
        .into_iter()
        .map(|e| e.health.filter(|h| !h.is_empty()))
        .collect()
}

async fn compose_project_status_raw(mode: ComposeMode, socket: &str, project: &str) -> Option<String> {
    let bin = match mode {
        ComposeMode::Plugin => "docker",
        ComposeMode::Standalone => "docker-compose",
    };
    let mut args: Vec<String> = match mode {
        ComposeMode::Plugin => vec!["-H".to_string(), socket.to_string(), "compose".to_string()],
        ComposeMode::Standalone => Vec::new(),
    };
    args.push("ls".to_string());
    args.push("-a".to_string());
    args.push("--format".to_string());
    args.push("json".to_string());
    let arg_refs: Vec<&str> = args.iter().map(String::as_str).collect();
    let stdout = match mode {
        ComposeMode::Plugin => exec::run(bin, &arg_refs).await,
        ComposeMode::Standalone => exec::run_with_env(bin, &arg_refs, &[("DOCKER_HOST", socket)]).await,
    }
    .ok()?;
    let projects = compose::parse_compose_projects(&stdout).ok()?;
    projects.into_iter().find(|p| p.name == project).map(|p| p.status)
}

/// `compose_projects`-style status lookup for one project, used by
