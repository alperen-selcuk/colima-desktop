/// Collect the set of host-bound ports currently considered "taken" for a
/// profile: docker-published ports (from `list_containers`) plus ports
/// reserved by other marketplace instances' `.env` files. Does not include
/// the live-bind test, which `resolve_free_port` does per-candidate.
async fn collect_taken_ports(app: &AppHandle, state: &AppState, profile: &str, exclude_project: Option<&str>) -> HashSet<u16> {
    let mut taken = HashSet::new();
    let socket = resolve_docker_socket(state, profile).await;
    if let Ok(stdout) = exec::run("docker", &["-H", &socket, "ps", "-a", "--no-trunc", "--format", "{{json .}}"]).await {
        if let Ok(raw) = exec::parse_json_lines::<RawContainerPorts>(&stdout) {
            for entry in raw {
                taken.extend(crate::docker::parse_port_links(&entry.ports).into_iter().map(|p| p.host_port));
            }
        }
    }
    if let Ok(app_data_dir) = app_data_dir_of(app) {
        let profile_dir = profile_marketplace_dir(&app_data_dir, profile);
        taken.extend(ports_reserved_by_other_instances(&profile_dir, exclude_project));
    }
    taken
}

/// Minimal shape of one `docker ps --format '{{json .}}'` line — just the
/// `Ports` field, for taken-port collection (the full `Container` type and
/// its label-enrichment pass live in `docker.rs` and aren't needed here).
#[derive(Debug, Deserialize)]
struct RawContainerPorts {
    #[serde(rename = "Ports", default)]
    ports: String,
}

#[tauri::command]
pub async fn marketplace_prepare(app: AppHandle, state: State<'_, AppState>, profile: String, item_id: String) -> Result<MarketplacePrepareResponse, String> {
    validate_profile_name(&profile)?;
    validate_item_id(&item_id)?;
    let item = find_catalog_item(&app, &item_id).await?;

    let app_data_dir = app_data_dir_of(&app)?;
    let profile_dir = profile_marketplace_dir(&app_data_dir, &profile);
    let existing_projects = list_instance_project_names(&profile_dir);
    let project_name = default_project_name(&item_id, &existing_projects);

    let mut taken_ports = collect_taken_ports(&app, &state, &profile, None).await;

    let mut variables = Vec::with_capacity(item.variables.len());
    for var in &item.variables {
        let value = match var.var_type.as_str() {
            "password" => generate_password(var.length.unwrap_or(24)),
            "port" => {
                let default_port: u16 = var
                    .default
                    .as_ref()
                    .and_then(|v| v.as_u64())
                    .and_then(|v| u16::try_from(v).ok())
                    .unwrap_or(0);
                let port = resolve_free_port(default_port, &taken_ports);
                taken_ports.insert(port);
                port.to_string()
            }
            _ => var
                .default
                .as_ref()
                .and_then(|v| v.as_str().map(str::to_string))
                .unwrap_or_default(),
        };
        variables.push(RenderedVariable {
            name: var.name.clone(),
            label: var.label.clone().unwrap_or_else(|| var.name.clone()),
            var_type: var.var_type.clone(),
            value,
            hidden: var.hidden,
        });
    }

    let preflight = run_preflight(&state, &profile, &item).await?;

    Ok(MarketplacePrepareResponse { project_name, variables, preflight })
}

/// List every existing instance project directory name under `profile_dir`.
fn list_instance_project_names(profile_dir: &Path) -> HashSet<String> {
    let Ok(entries) = std::fs::read_dir(profile_dir) else {
        return HashSet::new();
    };
    entries
        .flatten()
        .filter(|e| e.file_type().map(|t| t.is_dir()).unwrap_or(false))
        .map(|e| e.file_name().to_string_lossy().to_string())
        .collect()
}

