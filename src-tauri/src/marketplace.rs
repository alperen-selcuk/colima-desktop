/// Live end-to-end diagnostic against this machine's real colima (profile
/// `default`). Ignored by default: `cargo test live_marketplace_install_and_uninstall
/// -- --ignored --nocapture`.
///
/// Colima's `default` profile may be stopped on the machine running this
/// test — if so, the test prints a message and returns early rather than
/// starting/stopping colima itself (never do that from a test, per
/// AGENTS.md). If running, it installs a light built-in catalog item
/// (preferring `mailpit` if present, else the first item with an `http`
/// ready check) into a scratch `<app_data_dir>/marketplace/default/` under a
/// throwaway app-data directory, waits for its primary endpoint to answer
/// 200, then uninstalls with `removeVolumes: true`. It only ever touches
/// compose projects named `cd-livetest-*`, mirroring `compose.rs`'s
/// `live_compose_up_and_down`, and calls the underlying async helpers
/// directly (no `AppHandle`/`State` mock harness exists in this crate).
#[cfg(test)]
mod live_tests {
    use super::*;

    async fn colima_default_running() -> bool {
        matches!(
            exec::run("colima", &["status", "--json", "-p", "default"]).await,
            Ok(stdout) if serde_json::from_str::<serde_json::Value>(stdout.trim()).is_ok()
        )
    }

    #[tokio::test]
    #[ignore]
    async fn live_marketplace_install_and_uninstall() {
        if !colima_default_running().await {
            println!("colima profile `default` is not running — skipping live marketplace test");
            return;
        }

        let items = builtin_catalog_items();
        if items.is_empty() {
            println!("built-in catalog is empty (placeholder not yet replaced by the catalog build) — skipping");
            return;
        }
        let item = items
            .iter()
            .find(|i| i.id == "mailpit")
            .or_else(|| items.iter().find(|i| matches!(i.ready, Some(CatalogReady::Http { .. })) && !i.compose.trim().is_empty()))
            .expect("expected at least one http-ready catalog item for the live test");
        println!("using catalog item: {}", item.id);

        let profile = "default";
        let state = AppState::default();
        let socket = resolve_docker_socket(&state, profile).await;
        let mode = compose::resolve_compose_info(&state, profile, &socket)
            .await
            .mode
            .expect("docker compose must be available on this machine");

        let scratch_app_data = std::env::temp_dir().join(format!(
            "colima-desktop-live-marketplace-{}-{}",
            std::process::id(),
            std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos()
        ));
        let project = "cd-livetest-marketplace".to_string();
        let dir = instance_dir(&scratch_app_data, profile, &project);

        // Clean slate: bring down any leftover project with this name.
        if let Ok((down_bin, down_args)) = compose::build_action_args(mode, &socket, &project, "down", &[], true) {
            let down_arg_refs: Vec<&str> = down_args.iter().map(String::as_str).collect();
            let env = compose_env_for_mode(mode, &socket);
            let env_refs: Vec<(&str, &str)> = env.iter().map(|(k, v)| (k.as_str(), v.as_str())).collect();
            match mode {
                ComposeMode::Plugin => {
                    let _ = exec::run(&down_bin, &down_arg_refs).await;
                }
                ComposeMode::Standalone => {
                    let _ = exec::run_with_env(&down_bin, &down_arg_refs, &env_refs).await;
                }
            }
        }

        // Render values: passwords + a high scratch port range unlikely to
        // collide, deterministic ports picked the same way `marketplace_prepare` does.
        let mut values: HashMap<String, String> = HashMap::new();
        let mut var_order = Vec::new();
        let mut taken_ports = HashSet::new();
        for var in &item.variables {
            var_order.push(var.name.clone());
            let value = match var.var_type.as_str() {
                "password" => generate_password(var.length.unwrap_or(24)),
                "port" => {
                    let default_port: u16 = var.default.as_ref().and_then(|v| v.as_u64()).and_then(|v| u16::try_from(v).ok()).unwrap_or(18025);
                    let port = resolve_free_port(default_port, &taken_ports);
                    taken_ports.insert(port);
                    port.to_string()
                }
                _ => var.default.as_ref().and_then(|v| v.as_str().map(str::to_string)).unwrap_or_default(),
            };
            values.insert(var.name.clone(), value);
        }
        println!("rendered {} variable(s) for {}", values.len(), item.id);

        // Write compose.yml + .env (mirrors marketplace_install).
        std::fs::create_dir_all(&dir).unwrap();
        let compose_path = dir.join("compose.yml");
        write_atomically(&compose_path, item.compose.as_bytes(), None).expect("write compose.yml");
        let env_pairs = build_env_pairs(&values, &project, &var_order);
        let env_content = serialize_env_file(&env_pairs);
        write_atomically(&dir.join(".env"), env_content.as_bytes(), Some(0o600)).expect("write .env");

        // compose up -d
        let compose_files = vec![compose_path.to_string_lossy().to_string()];
        let (bin, args) = compose::build_up_args(
            mode,
            &socket,
            &compose_files,
            Some(&project),
            &ComposeUpOptions { build: false, pull: "missing".to_string(), force_recreate: false },
        );
        let arg_refs: Vec<&str> = args.iter().map(String::as_str).collect();
        let env = compose_env_for_mode(mode, &socket);
        let env_refs: Vec<(&str, &str)> = env.iter().map(|(k, v)| (k.as_str(), v.as_str())).collect();
        let up_result = match mode {
            ComposeMode::Plugin => exec::run(&bin, &arg_refs).await,
            ComposeMode::Standalone => exec::run_with_env(&bin, &arg_refs, &env_refs).await,
        };
        up_result.expect("compose up should succeed for the live-test item");
        println!("compose up succeeded for project {project}");

        // Wait for the primary endpoint to answer, using the same
        // ready-condition evaluation as `marketplace_install`.
        if let Some(ready) = &item.ready {
            let deadline = tokio::time::Instant::now()
                + Duration::from_secs(match ready {
                    CatalogReady::Http { timeout_sec, .. } => *timeout_sec,
                    CatalogReady::Healthy { timeout_sec } => *timeout_sec,
                    CatalogReady::Running { timeout_sec } => *timeout_sec,
                });
            loop {
                let is_ready = match ready {
                    CatalogReady::Http { url, expect_status, .. } => poll_http_ready(&render_template(url, &values), expect_status).await,
                    CatalogReady::Healthy { .. } => poll_healthy_ready(mode, &socket, &project).await,
                    CatalogReady::Running { .. } => poll_running_ready(mode, &socket, &project).await,
                };
                if is_ready {
                    break;
                }
                assert!(tokio::time::Instant::now() < deadline, "timed out waiting for {} to become ready", item.id);
                tokio::time::sleep(Duration::from_secs(2)).await;
            }
        }
        println!("{} became ready", item.id);

        let endpoints = render_endpoints(&item.endpoints, &values);
        let primary = endpoints.iter().find(|e| e.primary).or_else(|| endpoints.first());
        if let Some(primary) = primary {
            if let Some(url) = &primary.url {
                let client = reqwest::Client::builder().timeout(Duration::from_secs(10)).build().unwrap();
                let resp = client.get(url).send().await.expect("primary endpoint should respond");
                assert!(resp.status().is_success() || resp.status().as_u16() < 500, "expected a non-5xx response from {url}, got {}", resp.status());
                println!("GET {url} -> {}", resp.status());
            }
        }

        // Uninstall: compose down -v --remove-orphans, then remove the
        // instance dir (mirrors marketplace_uninstall).
        let (down_bin, down_args) = compose::build_action_args(mode, &socket, &project, "down", &compose_files, true).unwrap();
        let down_arg_refs: Vec<&str> = down_args.iter().map(String::as_str).collect();
        let down_result = match mode {
            ComposeMode::Plugin => exec::run(&down_bin, &down_arg_refs).await,
            ComposeMode::Standalone => exec::run_with_env(&down_bin, &down_arg_refs, &env_refs).await,
        };
        down_result.expect("compose down should succeed");
        std::fs::remove_dir_all(&dir).ok();
        std::fs::remove_dir_all(&scratch_app_data).ok();
        println!("cd-livetest-marketplace uninstalled and scratch dir removed");
    }
}
