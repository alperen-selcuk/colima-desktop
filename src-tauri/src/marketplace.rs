#[tauri::command]
pub async fn marketplace_installed(app: AppHandle, state: State<'_, AppState>, profile: String) -> Result<Vec<InstalledApp>, String> {
    validate_profile_name(&profile)?;
    let app_data_dir = app_data_dir_of(&app)?;
    let profile_dir = profile_marketplace_dir(&app_data_dir, &profile);

    let Ok(entries) = std::fs::read_dir(&profile_dir) else {
        return Ok(Vec::new());
    };

    let socket = resolve_docker_socket(&state, &profile).await;
    let mode = compose::resolve_compose_info(&state, &profile, &socket).await.mode;

    let mut projects_by_name: HashMap<String, String> = HashMap::new();
    if let Some(mode) = mode {
        let bin = match mode {
            ComposeMode::Plugin => "docker",
            ComposeMode::Standalone => "docker-compose",
        };
        let mut args: Vec<String> = match mode {
            ComposeMode::Plugin => vec!["-H".to_string(), socket.clone(), "compose".to_string()],
            ComposeMode::Standalone => Vec::new(),
        };
        args.push("ls".to_string());
        args.push("-a".to_string());
        args.push("--format".to_string());
        args.push("json".to_string());
        let arg_refs: Vec<&str> = args.iter().map(String::as_str).collect();
        let stdout = match mode {
            ComposeMode::Plugin => exec::run(bin, &arg_refs).await,
            ComposeMode::Standalone => exec::run_with_env(bin, &arg_refs, &[("DOCKER_HOST", &socket)]).await,
        };
        if let Ok(stdout) = stdout {
            if let Ok(projects) = compose::parse_compose_projects(&stdout) {
                for p in projects {
                    projects_by_name.insert(p.name, p.status);
                }
            }
        }
    }

    let mut apps = Vec::new();
    for entry in entries.flatten() {
        if !entry.file_type().map(|t| t.is_dir()).unwrap_or(false) {
            continue;
        }
        let manifest_path = entry.path().join("instance.json");
        let Ok(content) = std::fs::read_to_string(&manifest_path) else { continue };
        let Ok(manifest): Result<InstanceManifest, _> = serde_json::from_str(&content) else { continue };

        // Try to resolve endpoints/notes from the currently-known catalog
        // item; if the item has since disappeared from the catalog, fall
        // back to rendering with no endpoints rather than failing the whole
        // list.
        let (endpoints, notes) = match find_catalog_item(&app, &manifest.item_id).await {
            Ok(item) => (render_endpoints(&item.endpoints, &manifest.values), item.notes),
            Err(_) => (Vec::new(), None),
        };

        let status = projects_by_name.get(&manifest.project_name).cloned().unwrap_or_else(|| "missing".to_string());

        apps.push(InstalledApp {
            project_name: manifest.project_name,
            item_id: manifest.item_id,
            name: manifest.name,
            icon: manifest.icon,
            created_at: manifest.created_at,
            status,
            endpoints,
            notes,
        });
    }

    apps.sort_by(|a, b| a.created_at.cmp(&b.created_at));
    Ok(apps)
}

